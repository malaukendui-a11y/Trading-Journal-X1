/**
 * Mengambil nilai string terjemahan berdasarkan path dot notation.
 *
 * @param {string} lang Kode bahasa ('id' | 'en')
 * @param {string} path Key terjemahan bertitik (misal: 'nav.dashboard')
 * @param {Object} [params] Objek interpolasi nilai, misal { count: 3 } untuk '{count}'
 * @returns {string} String terjemahan atau key fallback bila tidak ditemukan
 */
export function translate(lang, path, params = {}) {
  const selectedLang = lang === 'en' ? 'en' : 'id'
  const keys = path.split('.')

  let current = translations[selectedLang]
  for (const k of keys) {
    if (current && typeof current === 'object' && k in current) {
      current = current[k]
    } else {
      // Fallback ke bahasa Indonesia jika missing di bahasa Inggris
      let fallback = translations.id
      for (const fk of keys) {
        if (fallback && typeof fallback === 'object' && fk in fallback) {
          fallback = fallback[fk]
        } else {
          return path
        }
      }
      current = fallback
      break
    }
  }

  if (typeof current !== 'string') {
    return path
  }

  let result = current
  for (const [paramKey, paramValue] of Object.entries(params)) {
    result = result.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramValue))
  }

  return result
}
